function normalizeProviderModels(payload: unknown): CommandCodeModel[] | null {
  if (typeof payload !== 'object' || payload === null) return null;
  const data = (payload as { data?: unknown }).data;
  if (!Array.isArray(data)) return null;
  const models: CommandCodeModel[] = [];
  for (const raw of data) {
    if (typeof raw !== 'object' || raw === null) continue;
    const record = raw as { id?: unknown; name?: unknown };
    if (typeof record.id !== 'string' || !record.id) continue;
    models.push({ id: record.id, name: typeof record.name === 'string' && record.name ? record.name : record.id });
  }
  return models.length > 0 ? models : null;
}

